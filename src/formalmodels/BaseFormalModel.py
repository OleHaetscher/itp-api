from __future__ import annotations

from abc import ABC, abstractmethod
from pathlib import Path
from typing import Any

from src.ITPSpecification import ITPSpecification


class BaseFormalModel(ABC):
    """
    Base class for formal models implemented inside the ITP codebase.

    Args:

    Returns:
    """

    specification = ITPSpecification()

    @abstractmethod
    def __init__(self) -> None:
        """
        Initialize the formal model.

        Args:

        Returns:
        """

        pass

    @abstractmethod
    def integrate_numerical_input(
        self,
        numerical_input: dict[str, float],
        context: str | None = None,
    ) -> None:
        """
        Integrate numerical input into the model state.

        Args:
            numerical_input: Numerical input received by the model.
            context: Optional string describing the interaction context.

        Returns:
        """

        pass

    @abstractmethod
    def generate_numerical_output(
        self,
        context: str | None = None,
    ) -> dict[str, float]:
        """
        Generate numerical output from the current model state.

        Args:
            context: Optional string describing the interaction context.

        Returns:
            Numerical output generated by the model.
        """

        pass

    def from_message(
        self,
        message: dict[str, Any],
    ) -> None:
        """
        Integrate a numerical ITP message into the model.

        Args:
            message: Numerical ITP message.

        Returns:
        """

        self.validate_model_interface()

        self.specification.validate_message(
            message=message,
            allowed_dimensions=self.dimensions,
        )

        self.integrate_numerical_input(
            numerical_input=message["values"],
            context=message["context"],
        )

    def to_message(
        self,
        target_agent: str,
        timecode: dict[str, Any],
        context: str,
        metadata: dict[str, Any] | None = None,
    ) -> dict[str, Any]:
        """
        Generate a numerical ITP message from the model.

        Args:
            target_agent: Identifier of the receiving agent.
            timecode: Time information for the message.
            context: String describing the interaction context.
            metadata: Optional additional information.

        Returns:
            Numerical ITP message.
        """

        self.validate_model_interface()

        values = self.generate_numerical_output(context=context)

        message = self.specification.make_message(
            source_agent=self.model_id,
            target_agent=target_agent,
            timecode=timecode,
            values=values,
            context=context,
            metadata=metadata,
        )

        self.specification.validate_message(
            message=message,
            allowed_dimensions=self.dimensions,
        )

        return message

    def from_json(
        self,
        source: str | Path,
    ) -> None:
        """
        Integrate numerical input from a JSON message.

        Args:
            source: JSON string or path to a JSON file.

        Returns:
        """

        message = self.specification.from_json(source)
        self.from_message(message)

    def to_json(
        self,
        target_agent: str,
        timecode: dict[str, Any],
        context: str,
        metadata: dict[str, Any] | None = None,
        indent: int = 4,
    ) -> str:
        """
        Generate numerical output as a JSON message.

        Args:
            target_agent: Identifier of the receiving agent.
            timecode: Time information for the message.
            context: String describing the interaction context.
            metadata: Optional additional information.
            indent: Number of spaces used for JSON indentation.

        Returns:
            JSON representation of the model output.
        """

        message = self.to_message(
            target_agent=target_agent,
            timecode=timecode,
            context=context,
            metadata=metadata,
        )

        return self.specification.to_json(message, indent=indent)

    def save_json(
        self,
        path: str | Path,
        target_agent: str,
        timecode: dict[str, Any],
        context: str,
        metadata: dict[str, Any] | None = None,
        indent: int = 4,
    ) -> None:
        """
        Save numerical model output as a JSON message.

        Args:
            path: Path to the JSON file.
            target_agent: Identifier of the receiving agent.
            timecode: Time information for the message.
            context: String describing the interaction context.
            metadata: Optional additional information.
            indent: Number of spaces used for JSON indentation.

        Returns:
        """

        message = self.to_message(
            target_agent=target_agent,
            timecode=timecode,
            context=context,
            metadata=metadata,
        )

        self.specification.save_json(
            message=message,
            path=path,
            indent=indent,
        )

    def validate_model_interface(self) -> None:
        """
        Validate that the model exposes required shared attributes.

        Args:

        Returns:
        """

        required_attributes = ("model_id", "dimensions")

        for attribute in required_attributes:
            if not hasattr(self, attribute):
                raise AttributeError(f"Missing required model attribute: {attribute}")

        if not isinstance(self.model_id, str):
            raise TypeError("model_id must be a string.")

        if not isinstance(self.dimensions, tuple):
            raise TypeError("dimensions must be a tuple.")

        if not self.dimensions:
            raise ValueError("dimensions must contain at least one dimension.")

        unknown_dimensions = set(self.dimensions) - set(
            self.specification.allowed_dimensions
        )

        if unknown_dimensions:
            raise ValueError(f"Unknown model dimensions: {unknown_dimensions}")