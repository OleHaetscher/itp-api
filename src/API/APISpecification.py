from __future__ import annotations

from typing import Any

from fastapi import FastAPI, HTTPException

from src.FormalModels.BaseFormalModel import BaseFormalModel


class APISpecification:
    """
    REST API for exposing a formal model through the ITP framework.

    Args:

    Returns:
    """

    def __init__(self, model: BaseFormalModel) -> None:
        """
        Initialize the API for one formal model.

        Args:
            model: Formal model exposed through the API.

        Returns:
        """

        self.model = model
        self.app = FastAPI(title=f"ITP Formal Model API: {model.model_id}")

        self._register_routes()

    def _register_routes(self) -> None:
        """
        Register REST endpoints for the formal model API.

        Args:

        Returns:
        """

        @self.app.get("/info")
        def get_info() -> dict[str, Any]:
            return self.get_info()

        @self.app.post("/generate")
        def generate_message(request: dict[str, Any]) -> dict[str, Any]:
            return self._handle_endpoint_call(
                self.generate_message,
                request,
            )

        @self.app.post("/step")
        def step(message: dict[str, Any]) -> dict[str, Any]:
            return self._handle_endpoint_call(
                self.step,
                message,
            )

    def get_info(self) -> dict[str, Any]:
        """
        Return basic information about the exposed formal model.

        Args:

        Returns:
            Basic model information.
        """

        self.model.validate_model_interface()

        return {
            "model_id": self.model.model_id,
            "dimensions": list(self.model.dimensions),
            "schema_version": self.model.specification.schema_version,
        }

    def generate_message(self, request: dict[str, Any]) -> dict[str, Any]:
        """
        Generate an ITP message without integrating an incoming message first.

        Args:
            request: Request containing target model, interaction turn, and context.

        Returns:
            ITP message generated by the formal model.
        """

        target_model_id = self._get_required_value(request, "target_model_id")
        interaction_turn = self._get_required_value(request, "interaction_turn")
        context = self._get_required_value(request, "context")
        metadata = request.get("metadata")

        return self.model.to_message(
            target_model_id=target_model_id,
            interaction_turn=interaction_turn,
            context=context,
            metadata=metadata,
        )

    def step(self, message: dict[str, Any]) -> dict[str, Any]:
        """
        Integrate an incoming ITP message and generate a response message.

        Args:
            message: Incoming ITP message targeting the exposed formal model.

        Returns:
            ITP response message generated by the formal model.
        """

        self.model.specification.validate_message(
            message=message,
            allowed_dimensions=self.model.dimensions,
        )

        self._validate_message_target(message)

        self.model.from_message(message)

        return self.model.to_message(
            target_model_id=message["source_model_id"],
            interaction_turn=message["interaction_turn"],
            context=message["context"],
        )

    def _validate_message_target(self, message: dict[str, Any]) -> None:
        """
        Validate that an incoming message targets the exposed formal model.

        Args:
            message: Incoming ITP message.

        Returns:
        """

        if message["target_model_id"] != self.model.model_id:
            raise ValueError(
                f"Message targets {message['target_model_id']}, "
                f"but this API exposes {self.model.model_id}."
            )

    def _get_required_value(
        self,
        request: dict[str, Any],
        key: str,
    ) -> Any:
        """
        Extract a required value from an API request.

        Args:
            request: API request.
            key: Required key.

        Returns:
            Value stored under the required key.
        """

        if key not in request:
            raise ValueError(f"Missing required request key: {key}")

        if request[key] is None:
            raise ValueError(f"Request key must not be None: {key}")

        return request[key]

    def _handle_endpoint_call(
        self,
        endpoint_function,
        payload: dict[str, Any],
    ) -> dict[str, Any]:
        """
        Run an endpoint function and convert errors to HTTP errors.

        Args:
            endpoint_function: Function implementing the endpoint logic.
            payload: Payload passed to the endpoint function.

        Returns:
            Endpoint response.
        """

        try:
            return endpoint_function(payload)
        except (KeyError, TypeError, ValueError) as error:
            raise HTTPException(status_code=400, detail=str(error)) from error