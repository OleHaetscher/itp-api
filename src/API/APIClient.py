from __future__ import annotations

from typing import Any

import requests


class APIClient:
    """
    Client for communicating with a remote formal model API.

    Args:

    Returns:
    """

    def __init__(
        self,
        base_url: str,
        timeout: float = 10.0,
    ) -> None:
        """
        Initialize the API client.

        Args:
            base_url: Base URL of the remote formal model API.
            timeout: Request timeout in seconds.

        Returns:
        """

        self.base_url = base_url.rstrip("/")
        self.timeout = timeout

    def get_info(self) -> dict[str, Any]:
        """
        Get information about the remote formal model.

        Args:

        Returns:
            Basic model information.
        """

        return self._get("/info")

    def generate_message(
        self,
        target_agent: str,
        timecode: dict[str, Any],
        context: str,
        metadata: dict[str, Any] | None = None,
    ) -> dict[str, Any]:
        """
        Ask the remote model to generate an initial ITP message.

        Args:
            target_agent: Identifier of the agent receiving the generated message.
            timecode: Time information for the message.
            context: String describing the interaction context.
            metadata: Optional additional information.

        Returns:
            ITP message generated by the remote model.
        """

        request = {
            "target_agent": target_agent,
            "timecode": timecode,
            "context": context,
        }

        if metadata is not None:
            request["metadata"] = metadata

        return self._post("/generate", request)

    def step(
        self,
        message: dict[str, Any],
    ) -> dict[str, Any]:
        """
        Send an ITP message to the remote model and receive its response.

        Args:
            message: ITP message targeting the remote model.

        Returns:
            ITP message generated by the remote model.
        """

        return self._post("/step", message)

    def _get(
        self,
        endpoint: str,
    ) -> dict[str, Any]:
        """
        Send a GET request to the remote model API.

        Args:
            endpoint: API endpoint.

        Returns:
            JSON response.
        """

        response = requests.get(
            f"{self.base_url}{endpoint}",
            timeout=self.timeout,
        )
        response.raise_for_status()

        return response.json()

    def _post(
        self,
        endpoint: str,
        payload: dict[str, Any],
    ) -> dict[str, Any]:
        """
        Send a POST request to the remote model API.

        Args:
            endpoint: API endpoint.
            payload: JSON payload.

        Returns:
            JSON response.
        """

        response = requests.post(
            f"{self.base_url}{endpoint}",
            json=payload,
            timeout=self.timeout,
        )
        response.raise_for_status()

        return response.json()