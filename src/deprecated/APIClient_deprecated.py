from __future__ import annotations

from typing import Any

import requests


class APIClient:
    """
    Client for communicating with a remote formal model API.

    Args:

    Returns:
    """

    def __init__(
        self,
        base_url: str,
        timeout: float = 10.0,
    ) -> None:
        """
        Initialize the API client.

        Args:
            base_url: Base URL of the remote formal model API.
            timeout: Request timeout in seconds.

        Returns:
        """

        self.base_url = base_url.rstrip("/")
        self.timeout = timeout

    def get_info(
        self,
    ) -> dict[str, Any]:
        """
        Get information about the remote formal model.

        Args:

        Returns:
            Basic model information.
        """

        return self._get("/info")

    def get_agent(
        self,
    ) -> dict[str, str]:
        """
        Get the remote model agent description.

        Args:

        Returns:
            Remote model agent description.
        """

        return self.get_info()["agent"]

    def create_session(
        self,
        context: str,
    ) -> dict[str, Any]:
        """
        Create a session on the remote formal model API.

        Args:
            context: String describing the interaction context.

        Returns:
            Description of the created session.
        """

        return self._post("/sessions", {"context": context})

    def list_sessions(
        self,
    ) -> dict[str, Any]:
        """
        List the sessions open on the remote formal model API.

        Args:

        Returns:
            Identifiers of all open sessions.
        """

        return self._get("/sessions")

    def get_session_info(
        self,
        session_id: str,
    ) -> dict[str, Any]:
        """
        Get a description of one remote session.

        Args:
            session_id: Identifier of the remote session.

        Returns:
            Description of the session.
        """

        return self._get(f"/sessions/{session_id}")

    def delete_session(
        self,
        session_id: str,
    ) -> dict[str, Any]:
        """
        Delete one remote session and its stored messages.

        Args:
            session_id: Identifier of the remote session.

        Returns:
            Identifier of the deleted session.
        """

        return self._delete(f"/sessions/{session_id}")

    def get_messages(
        self,
        session_id: str,
    ) -> list[dict[str, Any]]:
        """
        Get all ITP messages stored in one remote session.

        Args:
            session_id: Identifier of the remote session.

        Returns:
            Stored ITP messages.
        """

        return self._get(f"/sessions/{session_id}/messages")["messages"]

    def generate_message(
        self,
        session_id: str,
        target_agent: dict[str, str],
        timecode: dict[str, Any] | None = None,
        metadata: dict[str, Any] | None = None,
    ) -> dict[str, Any]:
        """
        Ask the remote model to generate an ITP message.

        Args:
            session_id: Identifier of the remote session.
            target_agent: Agent receiving the generated message.
            timecode: Optional time information for the message.
            metadata: Optional additional information.

        Returns:
            ITP message generated by the remote model.
        """

        request: dict[str, Any] = {"target_agent": target_agent}

        if timecode is not None:
            request["timecode"] = timecode

        if metadata is not None:
            request["metadata"] = metadata

        return self._post(f"/sessions/{session_id}/generate", request)

    def step(
        self,
        session_id: str,
        message: dict[str, Any],
    ) -> dict[str, Any]:
        """
        Send an ITP message to the remote model and receive its response.

        Args:
            session_id: Identifier of the remote session.
            message: ITP message targeting the remote model.

        Returns:
            ITP message generated by the remote model.
        """

        return self._post(f"/sessions/{session_id}/step", message)

    def _get(
        self,
        endpoint: str,
    ) -> dict[str, Any]:
        """
        Send a GET request to the remote model API.

        Args:
            endpoint: API endpoint.

        Returns:
            JSON response.
        """

        response = requests.get(
            f"{self.base_url}{endpoint}",
            timeout=self.timeout,
        )
        response.raise_for_status()

        return response.json()

    def _post(
        self,
        endpoint: str,
        payload: dict[str, Any],
    ) -> dict[str, Any]:
        """
        Send a POST request to the remote model API.

        Args:
            endpoint: API endpoint.
            payload: JSON payload.

        Returns:
            JSON response.
        """

        response = requests.post(
            f"{self.base_url}{endpoint}",
            json=payload,
            timeout=self.timeout,
        )
        response.raise_for_status()

        return response.json()

    def _delete(
        self,
        endpoint: str,
    ) -> dict[str, Any]:
        """
        Send a DELETE request to the remote model API.

        Args:
            endpoint: API endpoint.

        Returns:
            JSON response.
        """

        response = requests.delete(
            f"{self.base_url}{endpoint}",
            timeout=self.timeout,
        )
        response.raise_for_status()

        return response.json()
